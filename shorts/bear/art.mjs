import { chromium } from 'playwright-core';
import http from 'http'; import fs from 'fs'; import path from 'path';
const root = process.cwd();
const types = { '.js': 'text/javascript', '.html': 'text/html', '.json': 'application/json' };
const srv = http.createServer((q, r) => { const p = path.join(root, decodeURIComponent(q.url.split('?')[0])); fs.readFile(p, (e, d) => { if (e) { r.writeHead(404); r.end(); return; } r.writeHead(200, { 'Content-Type': types[path.extname(p)] || 'application/octet-stream' }); r.end(d); }); }).listen(0);
const [kind, w, h, out] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: +w, height: +h } });
page.on('pageerror', e => { console.log('PAGEERR', e.message); process.exit(1); });
await page.goto(`http://localhost:${srv.address().port}/web/index.html?w=${w}&h=${h}&art=${kind}`);
await page.waitForFunction(() => window.ready, null, { timeout: 120000 }); await page.evaluate(() => window.ready);
if (fs.existsSync('web/overlay_art.js')) await page.addScriptTag({ path: 'web/overlay_art.js' });
const url = await page.evaluate((k) => { window.ART_KIND = k; window.renderArt(k); return window.grab('image/png', 1, 0); }, kind);
fs.writeFileSync(out, Buffer.from(url.split(',')[1], 'base64')); console.log('wrote', out);
await browser.close(); srv.close();
